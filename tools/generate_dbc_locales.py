#!/usr/bin/env python3
"""Generate localized-column metadata for a pinned WoWDBDefs build.

Definitions: https://github.com/wowdev/WoWDBDefs (CC BY-SA 4.0).
Only locstring fields are selected; numeric fields and ordinary asset paths
are never redirected. Generation rejects layouts it cannot represent.
"""
import argparse
from pathlib import Path
import re
import subprocess


def version(value):
    return tuple(map(int, value.split('.')))


def matches(line, build):
    for spec in line.removeprefix('BUILD ').split(', '):
        bounds = spec.split('-')
        if version(bounds[0]) <= build <= version(bounds[-1]):
            return True
    return False


def schema(path, build):
    blocks = re.split(r'\n\s*\n', path.read_text(encoding='utf-8-sig').strip())
    types = {}
    for line in blocks[0].splitlines()[1:]:
        line = line.split('//')[0].strip()
        if line:
            kind, name = line.split()[:2]
            types[name.rstrip('?')] = kind.split('<')[0]
    if 'locstring' not in types.values():
        return None
    candidates = []
    for block in blocks[1:]:
        lines = [line.split('//')[0].strip() for line in block.splitlines()]
        if not any(matches(line, build) for line in lines if line.startswith('BUILD ')):
            continue
        fields, localized = 0, []
        for line in lines:
            if not line or line.startswith(('BUILD ', 'LAYOUT ', 'COMMENT ')):
                continue
            if 'noninline' in line:
                raise ValueError(f'{path}: unexpected non-inline field in WDBC build')
            line = re.sub(r'^\$[^$]+\$', '', line)
            match = re.fullmatch(r'(\w+)\??(?:<u?(\d+)>)?(?:\[(\d+)\])?', line)
            if not match:
                raise ValueError(f'{path}: unsupported field {line}')
            name, bits, count = match.groups()
            count = int(count or 1)
            kind = types[name]
            if kind == 'locstring':
                localized.extend(fields + i * 17 for i in range(count))
                fields += 17 * count
            elif kind in ('float', 'string') or bits == '32':
                fields += count
            else:
                raise ValueError(f'{path}: unsupported WDBC width {line}')
        candidates.append((fields, localized))
    if not candidates:
        return None
    if any(candidate != candidates[0] for candidate in candidates):
        raise ValueError(f'{path}: conflicting build definitions')
    return candidates[0]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('definitions', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--build', default='3.3.5.12340')
    args = parser.parse_args()
    build = version(args.build)
    if build != (3, 3, 5, 12340):
        raise ValueError('This generator currently describes the 16-locale WDBC format of build 12340')
    revision = subprocess.check_output(['git', '-C', str(args.definitions.parent), 'rev-parse', 'HEAD'], text=True).strip()
    rows = []
    for path in sorted(args.definitions.glob('*.dbd')):
        result = schema(path, build)
        if result and result[1]:
            rows.append((path.stem.lower(), *result))
    lines = ['// Generated by tools/generate_dbc_locales.py; do not hand-edit.',
             '// WoWDBDefs ' + revision + ', build ' + args.build,
             '// https://github.com/wowdev/WoWDBDefs — schema data: CC BY-SA 4.0.',
             '// Only localized string fields; column counts checked before use.']
    for name, count, columns in rows:
        lines.append('static constexpr uint32_t locale_' + name + '[] = {' + ', '.join(map(str, columns)) + '};')
    lines.append('static constexpr LocaleSchema localeSchemas[] = {')
    for name, count, columns in rows:
        lines.append(f'    {{"{name}", {count}, locale_{name}}},')
    lines.append('};')
    args.output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'Generated {len(rows)} localized table layouts from {revision}')


if __name__ == '__main__':
    main()
